/* ============================================================================
 * Theory of Things — pure model functions
 * ----------------------------------------------------------------------------
 * Every function here implements an equation stated in one of the two source
 * documents:
 *   - The_Theory_of_Things_That_Are.md      (enthalpy, polarity, singularity,
 *                                            synergy, knowledge coefficients,
 *                                            observational geometry,
 *                                            projection/reflection)
 *   - The_Theory_of_Things_That_Are_Not.md (realized vs projected state,
 *                                            resolution difference)
 *
 * This file is environment-neutral: it is loaded by the browser dashboard and
 * by the Node verification harness. It must not touch the DOM.
 * ========================================================================== */
(function (root) {
  'use strict';

  /* Deterministic PRNG (mulberry32) so forecasts are reproducible. */
  function mulberry32(seed) {
    let a = seed >>> 0;
    return function () {
      a |= 0;
      a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function sign(v) { return v > 0 ? 1 : (v < 0 ? -1 : 0); }
  function clamp(v, lo, hi) { return v < lo ? lo : (v > hi ? hi : v); }
  function safeDiv(a, b) { return b === 0 ? 0 : a / b; }
  function round(v, d) {
    const m = Math.pow(10, d == null ? 6 : d);
    return Math.round(v * m) / m;
  }

  /* --- Enthalpy: H = U + PV ---------------------------------------------- */
  function enthalpy(U, P, V) { return U + P * V; }

  /* --- Knowledge coefficients: C_K = cos(theta), S_K = sin(theta) -------- */
  function knowledge(thetaDeg, k) {
    const th = (thetaDeg * Math.PI) / 180;
    const CK = Math.cos(th);
    const SK = Math.sin(th);
    return {
      thetaDeg: thetaDeg,
      theta: th,
      CK: CK,
      SK: SK,
      Kpar: k * CK,
      Kperp: k * SK,
      magnitude: Math.abs(k)
    };
  }

  /* --- Observational geometry: delta ~ B / D, resolved when delta > eps --- */
  function parallax(B, D) { return D === 0 ? Infinity : B / D; }
  function resolution(B, D, epsilon) {
    const delta = parallax(B, D);
    const ratio = epsilon > 0 ? delta / epsilon : Infinity;
    return {
      delta: delta,
      epsilon: epsilon,
      ratio: ratio,
      resolved: delta > epsilon
    };
  }

  /* --- N+1 reversal engine -------------------------------------------------
   * x[N+1] = x[N] + u[N] + f(x[N], u[N])
   * f is the induced system response (the counterforce generated by the
   * system's own operation). A reversal is reported when
   *   sign(x[N+1] - x[N]) != sign(u[N]).
   * ------------------------------------------------------------------------- */
  function nPlusOne(p) {
    const N = Math.max(2, Math.floor(p.horizon));
    const x = new Array(N + 1).fill(0);
    const u = new Array(N + 1).fill(0);
    const f = new Array(N + 1).fill(0);
    const H = new Array(N + 1).fill(0);
    const rev = new Array(N).fill(false);
    const U = new Array(N + 1).fill(0);

    x[0] = p.x0;
    for (let n = 0; n < N; n++) {
      u[n] = p.u0 + (p.uAmp || 0) * Math.sin(2 * Math.PI * (p.uFreq || 0) * n + (p.uPhase || 0));
      const fn = -(p.k1 * x[n] + p.k2 * x[n] * Math.abs(x[n]) + p.k3 * u[n] * x[n]);
      f[n] = fn;
      x[n + 1] = x[n] + u[n] + fn;
      U[n] = p.U0 + (p.alphaU || 0) * x[n];
      H[n] = enthalpy(U[n], p.P0, p.V0);
      const dx = x[n + 1] - x[n];
      rev[n] = (Math.abs(u[n]) > 1e-12 && Math.abs(dx) > 1e-12) ? (sign(dx) !== sign(u[n])) : false;
    }
    u[N] = p.u0 + (p.uAmp || 0) * Math.sin(2 * Math.PI * (p.uFreq || 0) * N + (p.uPhase || 0));
    U[N] = p.U0 + (p.alphaU || 0) * x[N];
    H[N] = enthalpy(U[N], p.P0, p.V0);
    return { N: N, x: x, u: u, f: f, H: H, U: U, rev: rev };
  }

  /* --- Entropic polarity oscillator ---------------------------------------
   * Two poles share one entropic magnitude: E_C = +E, E_G = -E.
   * u transfers concentrated stock toward the generative pole; gamma is the
   * singularity coupling that redistributes between poles; kappa is the
   * regeneration/dissipation term. c + g is conserved.
   * ------------------------------------------------------------------------- */
  function polarity(p) {
    const N = Math.max(2, Math.floor(p.horizon));
    const c = new Array(N + 1).fill(0);
    const g = new Array(N + 1).fill(0);
    const pol = new Array(N + 1).fill(0);
    const EC = new Array(N + 1).fill(0);
    const EG = new Array(N + 1).fill(0);
    const rev = new Array(N).fill(false);
    const rnd = mulberry32(p.seed == null ? 1 : p.seed);

    c[0] = p.c0;
    g[0] = p.g0;
    for (let n = 0; n < N; n++) {
      const noise = (p.noise || 0) * (rnd() * 2 - 1);
      const dc = p.u0 - p.gamma * (c[n] - g[n]) - p.kappa * c[n] + noise;
      const dg = -p.u0 + p.gamma * (c[n] - g[n]) + p.kappa * c[n] - noise;
      c[n + 1] = Math.max(0, c[n] + dc);
      g[n + 1] = Math.max(0, g[n] + dg);
      const prevPol = safeDiv(c[n] - g[n], c[n] + g[n]);
      const nextPol = safeDiv(c[n + 1] - g[n + 1], c[n + 1] + g[n + 1]);
      rev[n] = Math.abs(prevPol) > 1e-9 && Math.abs(nextPol) > 1e-9 && sign(prevPol) !== sign(nextPol);
    }
    for (let n = 0; n <= N; n++) {
      const sum = c[n] + g[n];
      pol[n] = safeDiv(c[n] - g[n], sum);
      EC[n] = safeDiv(c[n] - g[n], 2);
      EG[n] = -EC[n];
    }
    return { N: N, c: c, g: g, pol: pol, EC: EC, EG: EG, rev: rev, total: c[N] + g[N] };
  }

  /* --- Extraction / sustainability / synergy ------------------------------
   * R[N+1] = R[N] + rho*R[N]*(1 - R[N]/K) - consumption - extraction
   * E_val  = V_captured - C_extraction = (price - cost) * extraction
   * S      = Regeneration - Consumption
   * Y      = V(A (+) B) - [V(A) + V(B)], with V(A (+) B) = (1 + s)(V(A)+V(B))
   * ------------------------------------------------------------------------- */
  function economy(p) {
    const N = Math.max(2, Math.floor(p.horizon));
    const R = new Array(N + 1).fill(0);
    const E = new Array(N + 1).fill(0);
    const S = new Array(N + 1).fill(0);
    const Y = new Array(N + 1).fill(0);
    const V = new Array(N + 1).fill(0);
    const rev = new Array(N).fill(false);
    const regen = new Array(N + 1).fill(0);
    const ex = new Array(N + 1).fill(0);
    const cons = new Array(N + 1).fill(0);

    R[0] = p.stock0;
    for (let n = 0; n < N; n++) {
      const rg = p.rho * R[n] * (1 - R[n] / p.K);
      const exn = Math.min(Math.max(0, p.extraction), Math.max(0, R[n]));
      const consn = Math.min(Math.max(0, p.consumption), Math.max(0, R[n] + rg));
      regen[n] = rg;
      ex[n] = exn;
      cons[n] = consn;
      R[n + 1] = Math.max(0, R[n] + rg - consn - exn);
      const VA = (p.price - p.cost) * exn;      // extraction value
      const VB = rg - consn;                   // sustainability value
      E[n] = VA;
      S[n] = VB;
      V[n] = VA + VB;
      Y[n] = p.synergy * (VA + VB);            // synergistic contribution
      rev[n] = exn > 0 && (R[n + 1] - R[n]) < 0; // strategy produces opposing result
    }
    regen[N] = p.rho * R[N] * (1 - R[N] / p.K);
    return { N: N, R: R, E: E, S: S, Y: Y, V: V, rev: rev, regen: regen, ex: ex, cons: cons };
  }

  /* --- Projection / reflection iteration -----------------------------------
   * State is a knowledge vector (C, S) on the unit circle with magnitude k.
   * Projection: rotate by phiP, scale magnitude by proj.
   * Reflection: reflect across the core axis (S -> -S), rotate by phiR,
   *             scale magnitude by refl.
   * K[N+1] = F(P(K[N])) with the direction normalised after each step.
   * ------------------------------------------------------------------------- */
  function knowledgeIteration(p) {
    const N = Math.max(2, Math.floor(p.iterations));
    let theta = (p.theta0 * Math.PI) / 180;
    let k = p.k0;
    const xs = [], ys = [], mags = [], coh = [];
    const phiP = (p.projAngle * Math.PI) / 180;
    const phiR = (p.reflAngle * Math.PI) / 180;

    for (let n = 0; n <= N; n++) {
      const C = Math.cos(theta), S = Math.sin(theta);
      xs.push(C); ys.push(S); mags.push(k);
      if (n < N) {
        const C1 = p.proj * (C * Math.cos(phiP) - S * Math.sin(phiP));
        const S1 = p.proj * (C * Math.sin(phiP) + S * Math.cos(phiP));
        const Sr = -S1; // reflection across the core (C) axis
        const C2 = p.refl * (C1 * Math.cos(phiR) - Sr * Math.sin(phiR));
        const S2 = p.refl * (C1 * Math.sin(phiR) + Sr * Math.cos(phiR));
        const len = Math.hypot(C2, S2) || 1;
        const newTheta = Math.atan2(S2 / len, C2 / len);
        let dTheta = newTheta - theta;
        while (dTheta > Math.PI) dTheta -= 2 * Math.PI;
        while (dTheta < -Math.PI) dTheta += 2 * Math.PI;
        coh.push(Math.cos(dTheta)); // 1 = perfectly coherent step
        theta = newTheta;
        k = k * p.proj * p.refl;
      }
    }
    return { N: N, xs: xs, ys: ys, mags: mags, coh: coh, thetaFinal: theta * 180 / Math.PI };
  }

  /* --- Realized vs projected state (Theory of Things That Are Not) ---------
   * Realized:   x[N+1]  = x[N] + u + f_true(x[N])  + eta[N]
   * Projection: xhat[N+1] = x[N] + u + f_model(x[N]) + bias
   * Resolution difference: delta[N+1] = x[N+1] - xhat[N+1]
   * Also returns an open-loop projection (model run on its own state).
   * ------------------------------------------------------------------------- */
  function prediction(p) {
    const N = Math.max(2, Math.floor(p.horizon));
    const rnd = mulberry32(p.seed == null ? 1 : p.seed);
    const x = new Array(N + 1).fill(0);
    const xh = new Array(N + 1).fill(0);
    const xhOpen = new Array(N + 1).fill(0);
    const d = new Array(N + 1).fill(0);
    const eta = new Array(N + 1).fill(0);

    x[0] = p.x0;
    xh[0] = p.x0;
    xhOpen[0] = p.x0;
    for (let n = 0; n < N; n++) {
      const u = p.u0;
      const fTrue = -(p.k1t * x[n] + p.k2t * x[n] * Math.abs(x[n]));
      const e = (p.noise || 0) * (rnd() * 2 - 1);
      eta[n] = e;
      x[n + 1] = x[n] + u + fTrue + e;

      const fModel = -(p.k1m * x[n] + p.k2m * x[n] * Math.abs(x[n])) + (p.bias || 0);
      xh[n + 1] = x[n] + u + fModel;            // one-step projection from realized state
      xhOpen[n + 1] = xhOpen[n] + u - (p.k1m * xhOpen[n] + p.k2m * xhOpen[n] * Math.abs(xhOpen[n])) + (p.bias || 0);
      d[n + 1] = x[n + 1] - xh[n + 1];
    }
    return { N: N, x: x, xh: xh, xhOpen: xhOpen, d: d, eta: eta };
  }

  /* --- Monte Carlo over the nondeterminative factor eta -------------------- */
  function monteCarlo(p) {
    const M = Math.max(1, Math.floor(p.runs));
    const N = Math.max(2, Math.floor(p.horizon));
    const runs = [];
    for (let m = 0; m < M; m++) {
      runs.push(prediction({
        horizon: p.horizon,
        x0: p.x0,
        u0: p.u0,
        k1t: p.k1t,
        k2t: p.k2t,
        k1m: p.k1m,
        k2m: p.k2m,
        bias: p.bias || 0,
        noise: p.noise || 0,
        seed: (p.seed == null ? 1 : p.seed) + m * 1013904223
      }));
    }
    function pct(col, q) {
      const a = col.slice().sort(function (a, b) { return a - b; });
      const i = Math.min(a.length - 1, Math.max(0, Math.floor(q * (a.length - 1))));
      return a[i];
    }
    const mean = new Array(N + 1).fill(0);
    const p5 = new Array(N + 1).fill(0);
    const p95 = new Array(N + 1).fill(0);
    for (let n = 0; n <= N; n++) {
      const col = runs.map(function (r) { return r.x[n]; });
      const sum = col.reduce(function (a, b) { return a + b; }, 0);
      mean[n] = sum / M;
      p5[n] = pct(col, 0.05);
      p95[n] = pct(col, 0.95);
    }
    return { N: N, M: M, mean: mean, p5: p5, p95: p95, runs: runs };
  }

  const api = {
    mulberry32: mulberry32,
    sign: sign,
    clamp: clamp,
    safeDiv: safeDiv,
    round: round,
    enthalpy: enthalpy,
    knowledge: knowledge,
    parallax: parallax,
    resolution: resolution,
    nPlusOne: nPlusOne,
    polarity: polarity,
    economy: economy,
    knowledgeIteration: knowledgeIteration,
    prediction: prediction,
    monteCarlo: monteCarlo
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.TOT = api;
})(typeof window !== 'undefined' ? window : globalThis);
